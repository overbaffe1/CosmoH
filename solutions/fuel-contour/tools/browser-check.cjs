// Optional real Chromium E2E + printing. See RUNBOOK for isolated npm installation.
const {chromium: playwright} = require('playwright-core');
const chromium = require('@sparticuz/chromium');
const path = require('path');
const fs = require('fs');
(async()=>{
 const root=path.resolve(__dirname,'..');
 fs.mkdirSync(path.join(root,'results'),{recursive:true});
 const browser=await playwright.launch({executablePath:await chromium.executablePath(),args:chromium.args,headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.APP_URL||'http://127.0.0.1:8000');
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 if(!(await page.locator('#violations').textContent()).includes('Все проверки'))throw Error('Initial BASE not feasible');
 await page.locator('#plainHelp summary').click();
 if(!(await page.locator('#plainHelp').textContent()).includes('космическую заправку'))throw Error('Plain-language help missing');
 await page.locator('#plainHelp summary').click();
 await page.locator('#stress').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('MANDATORY_STRESS'));
 if(!(await page.locator('#violations').textContent()).includes('RESERVE_45D'))throw Error('Stress violations absent');
 await page.locator('#base').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('BASE'));
 await page.locator('#ordered').fill('0');await page.locator('#apply').click();await page.locator('#base').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 if((await page.locator('#violations').textContent()).includes('Все проверки'))throw Error('Changed plan did not recalculate');
 await page.locator('#loadDefault').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 const save=page.waitForEvent('download');await page.locator('#save').click();
 const download=await save;await download.saveAs(path.join(root,'results/browser-plan.json'));
 await page.locator('#file').setInputFiles(path.join(root,'results/browser-plan.json'));
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 await page.locator('[data-analysis="sensitivity"]').click();
 await page.waitForFunction(()=>document.querySelector('#analysisResult').textContent.includes('service_failure_bracket'));
 await page.locator('#compare').click();
 await page.waitForFunction(()=>document.querySelector('#analysisTitle').textContent==='Один план. Два сценария.');
 await page.locator('#researchEditor').evaluate(el=>el.closest('details').open=true);
 await page.locator('#researchRun').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('TEAM_GEO_CUSTOM'));
 await page.locator('#base').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('BASE'));
 // v0.2: explicit stress design, investment form, discounting and research-project roundtrip.
 await page.locator('#strategy').selectOption('earth-stress');await page.locator('#loadDefault').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 if(!(await page.locator('#violations').textContent()).includes('Все проверки'))throw Error('Prepared stress is not feasible');
 if(!(await page.locator('#scenarioBadge').textContent()).includes('MANDATORY_STRESS'))throw Error('Stress preset wrong environment');
 await page.locator('#investmentEditor').evaluate(el=>el.closest('details').open=true);
 await page.locator('#invest-ZBO').uncheck();await page.locator('#applyInvestments').click();await page.locator('#stress').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 if(!(await page.locator('#violations').textContent()).includes('STRESS_LOSS_LIMIT'))throw Error('Investment edit not applied');
 await page.locator('#strategy').selectOption('earth');await page.locator('#loadDefault').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 await page.locator('#rate').fill('0.05');await page.locator('#apply').click();await page.locator('#base').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Готово'));
 if(!(await page.locator('#economicSummary').textContent()).includes('ставка 5%'))throw Error('Real rate not displayed');
 await page.locator('[data-analysis="parameters"]').click();
 await page.waitForFunction(()=>document.querySelector('#analysisResult').textContent.includes('lead_time_policy'));
 await page.locator('#caseEditor').evaluate(el=>el.closest('details').open=true);
 const patch=JSON.parse(await page.locator('#caseEditor').inputValue());patch.demand[0].base_total_t=105;patch.basis='E2E research +5 tonnes';
 await page.locator('#caseEditor').fill(JSON.stringify(patch));await page.locator('#runCaseCopy').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('TEAM_INPUT_COPY'));
 const projectDownload=page.waitForEvent('download');await page.locator('#saveProject').click();
 await (await projectDownload).saveAs(path.join(root,'results/browser-project.json'));
 await page.locator('#restoreControl').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('BASE'));
 await page.locator('#file').setInputFiles(path.join(root,'results/browser-project.json'));
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('TEAM_INPUT_COPY'));
 if(!(await page.locator('#balance').textContent()).includes('105'))throw Error('Research project did not restore modified demand');
 await page.locator('#restoreControl').click();
 await page.waitForFunction(()=>document.querySelector('#scenarioBadge').textContent.startsWith('BASE'));
 await page.locator('#compareDecisions').click();
 await page.waitForFunction(()=>document.querySelector('#analysisResult').textContent.includes('avoided_stress_shortage_t'));
 const exp=page.waitForEvent('download');await page.locator('#export').click();
 await (await exp).saveAs(path.join(root,'results/browser-export.zip'));
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(root,'results/ui-desktop.png'),fullPage:true});
 await page.screenshot({path:path.join(root,'results/ui-viewport.png')});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#plainHelp').evaluate(el=>el.open=true);
 await page.screenshot({path:path.join(root,'results/ui-mobile.png'),fullPage:true});
 const overflowing=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflowing)throw Error('Mobile horizontal page overflow');
 for(const name of ['REPORT','COMPARISON','PRESENTATION']){
   await page.goto('file://'+path.join(root,'docs',name+'.html'));
   await page.emulateMedia({media:'print'});
   if(name==='PRESENTATION'){
     const issues=await page.evaluate(()=>Array.from(document.querySelectorAll('article')).flatMap((a,i)=>{
       const bottom=Math.max(...Array.from(a.querySelector('.content').children).map(el=>el.getBoundingClientRect().bottom));
       const box=a.querySelector('.takeaway').getBoundingClientRect(),footer=a.querySelector('footer').getBoundingClientRect();
       return bottom>box.top-4||box.bottom>footer.top?[i+1]:[];
     }));
     if(issues.length)throw Error('Slide content overlap: '+issues.join(','));
   }
   await page.pdf({path:path.join(root,'results',name+'.pdf'),preferCSSPageSize:true,printBackground:true});
 }
 await browser.close();if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS Chromium: BASE/STRESS, prepared design, investments, rate, data copy, plan/project roundtrip, sensitivity, 2x2, ZIP, mobile, PDF');
})().catch(e=>{console.error(e);process.exit(1)});
